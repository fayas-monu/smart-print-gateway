/*
 * AL SHAJAR STATIONERY — Smart Print Gateway
 * Built-in 10-page sample PDF. (AL SHAJAR TEAM)
 * Pure ASCII so PDF byte offsets stay simple. No dependencies.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SamplePdf = factory();
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  const encoder = new TextEncoder();
  const PAGE_W = 595.28;
  const PAGE_H = 841.89;
  const TOTAL = 10;

  function esc(value) {
    return String(value).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  }

  function contentFor(index) {
    const isCover = index === 0;
    const palette = ['0.078 0.353 0.267', '0.788 0.635 0.294', '0.957 0.945 0.918', '0.118 0.463 0.361'];
    const accent = palette[index % palette.length];
    const lines = [];

    lines.push('0.043 0.149 0.114 rg 0 0 ' + PAGE_W + ' ' + PAGE_H + ' re f');
    lines.push(accent + ' rg 0 ' + (PAGE_H - 9) + ' ' + PAGE_W + ' 9 re f');

    if (isCover) {
      lines.push('0.957 0.945 0.918 rg BT /F2 13 Tf 46 ' + (PAGE_H - 66) + ' Td (AL SHAJAR STATIONERY) Tj ET');
      lines.push('0.788 0.635 0.294 rg BT /F1 9 Tf 400 ' + (PAGE_H - 64) + ' Td (SMART PRINT GATEWAY) Tj ET');
      lines.push('0.788 0.635 0.294 rg 46 604 92 5 re f');
      lines.push('1 1 1 rg BT /F2 33 Tf 46 548 Td (Print brilliantly.) Tj ET');
      lines.push('0.788 0.9 0.82 rg BT /F1 13 Tf 46 515 Td (A sample file for Al Shajar Stationery customers.) Tj ET');
      lines.push('0.75 0.82 0.78 rg BT /F1 10.5 Tf 46 494 Td (Try black and white, colour, duplex, 2-up and 4-up previews.) Tj ET');
      lines.push('0.957 0.945 0.918 rg 46 322 502 128 re f');
      lines.push('0.043 0.149 0.114 rg BT /F2 13 Tf 66 418 Td (THIS PDF HAS 10 PAGES) Tj ET');
      lines.push('0.23 0.31 0.27 rg BT /F1 10 Tf 66 394 Td (Black and white A4/A5: AED 1.00 for every 8 pages, or part of 8.) Tj ET');
      lines.push('0.23 0.31 0.27 rg BT /F1 10 Tf 66 376 Td (9-16 pages = AED 2.00. Colour A4/A5: AED 1.00 per page.) Tj ET');
      lines.push('0.23 0.31 0.27 rg BT /F1 10 Tf 66 358 Td (All prices already include 5% UAE VAT. No VAT is added on top.) Tj ET');
      lines.push('0.788 0.635 0.294 rg 46 238 118 118 re f');
      lines.push('0.118 0.463 0.361 rg 176 238 118 118 re f');
      lines.push('0.957 0.945 0.918 rg 306 238 118 118 re f');
      lines.push('0.85 0.45 0.35 rg 436 238 112 118 re f');
      lines.push('0.62 0.7 0.65 rg BT /F1 8.5 Tf 46 206 Td (Sample document  |  Generated by the Smart Print Gateway  |  Al Shajar Stationery) Tj ET');
    } else {
      lines.push('0.957 0.945 0.918 rg BT /F2 25 Tf 46 700 Td (Sample page ' + (index + 1) + ') Tj ET');
      lines.push('0.788 0.635 0.294 rg 46 676 70 5 re f');
      lines.push('0.75 0.82 0.78 rg BT /F1 10.5 Tf 46 642 Td (This page demonstrates the layout you will see in the live preview.) Tj ET');
      lines.push('0.75 0.82 0.78 rg BT /F1 10.5 Tf 46 624 Td (Margins, orientation, N-up and duplex are applied to every page.) Tj ET');

      for (let i = 0; i < 12; i += 1) {
        const width = 300 + ((i * 37) % 150);
        lines.push('0.28 0.38 0.34 rg 46 ' + (574 - i * 22) + ' ' + width + ' 6 re f');
      }

      lines.push('0.957 0.945 0.918 rg 46 258 500 112 re f');
      lines.push('0.788 0.635 0.294 rg 46 258 6 112 re f');
      lines.push('0.043 0.149 0.114 rg BT /F2 12 Tf 66 338 Td (Smart print tip ' + index + ') Tj ET');
      const tips = [
        'A4 and A5 black & white share the same simple rate.',
        '1-8 pages cost AED 1.00. 9-16 pages cost AED 2.00.',
        'Colour A4 and A5 pages are AED 1.00 per page.',
        'A3 black & white is AED 2.00 per page; A3 colour is AED 3.00.',
        'Double-sided printing halves the paper without changing the page price.',
        '2-up or 4-up puts more pages on each sheet and saves paper.',
        'All listed prices include UAE VAT. The receipt reverses VAT for clarity.',
        'Home delivery is free on orders of AED 50.00 or more.',
        'Choose cash or card when you send your job.'
      ];
      lines.push('0.23 0.31 0.27 rg BT /F1 9.5 Tf 66 313 Td (' + esc(tips[(index - 1) % tips.length]) + ') Tj ET');
      lines.push('0.23 0.31 0.27 rg BT /F1 9.5 Tf 66 294 Td (Our team checks every job before it is printed.) Tj ET');
    }

    lines.push('0.55 0.64 0.59 rg BT /F1 8.5 Tf 46 34 Td (AL SHAJAR STATIONERY  |  Smart Print Gateway  |  Page ' + (index + 1) + ' of ' + TOTAL + ') Tj ET');
    lines.push('0.55 0.64 0.59 rg BT /F1 8.5 Tf 510 34 Td (' + (index + 1) + '/' + TOTAL + ') Tj ET');
    return lines.join('\n');
  }

  function build() {
    const objects = [];
    const pageStart = 5;
    const kids = [];
    for (let i = 0; i < TOTAL; i += 1) kids.push((pageStart + i * 2) + ' 0 R');

    objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
    objects[2] = '<< /Type /Pages /Kids [' + kids.join(' ') + '] /Count ' + TOTAL + ' >>';
    objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>';
    objects[4] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>';

    for (let i = 0; i < TOTAL; i += 1) {
      const pageNum = pageStart + i * 2;
      const contentNum = pageNum + 1;
      const content = contentFor(i);
      objects[pageNum] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ' + PAGE_W + ' ' + PAGE_H +
        '] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ' + contentNum + ' 0 R >>';
      objects[contentNum] = '<< /Length ' + content.length + ' >>\nstream\n' + content + '\nendstream';
    }

    const totalObjects = 4 + TOTAL * 2;
    const chunks = [];
    let length = 0;
    function push(data) {
      const bytes = typeof data === 'string' ? encoder.encode(data) : data;
      chunks.push(bytes);
      length += bytes.length;
    }

    push('%PDF-1.4\n%\u00E2\u00E3\u00CF\u00D3\n');
    const offsets = [0];
    for (let i = 1; i <= totalObjects; i += 1) {
      offsets[i] = length;
      push(i + ' 0 obj\n' + objects[i] + '\nendobj\n');
    }
    const xrefStart = length;
    let xref = 'xref\n0 ' + (totalObjects + 1) + '\n0000000000 65535 f \n';
    for (let i = 1; i <= totalObjects; i += 1) {
      xref += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
    }
    push(xref);
    push('trailer\n<< /Size ' + (totalObjects + 1) + ' /Root 1 0 R >>\nstartxref\n' + xrefStart + '\n%%EOF\n');

    const out = new Uint8Array(length);
    let pos = 0;
    chunks.forEach(function (chunk) {
      out.set(chunk, pos);
      pos += chunk.length;
    });
    return out;
  }

  return { build: build, pageCount: TOTAL };
});
